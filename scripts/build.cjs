const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'dist');
const unpacked = path.join(dist, 'batch-grab-beta');
fs.mkdirSync(unpacked, { recursive: true });
const files = ['manifest.json', 'background.js', 'lib.js', 'popup.js', 'popup.html', 'popup.css'];
for (const file of files) fs.copyFileSync(path.join(root, file), path.join(unpacked, file));
const manifest = JSON.parse(fs.readFileSync(path.join(unpacked, 'manifest.json')));
if (manifest.manifest_version !== 3 || !manifest.background?.service_worker) throw Error('MV3 background worker required');
const zip = path.join(dist, `batch-grab-${manifest.version}-beta.zip`);
fs.rmSync(zip, { force: true });
execFileSync('/usr/bin/zip', ['-q', zip, ...files], { cwd: unpacked });
const demoZip = path.join(dist, 'batch-grab-demo.zip');
fs.rmSync(demoZip, { force: true });
execFileSync('/usr/bin/zip', ['-qr', demoZip, 'demo', 'scripts/demo-server.cjs'], { cwd: root });
const hashes = Object.fromEntries(files.map(file => [file, createHash('sha256').update(fs.readFileSync(path.join(unpacked, file))).digest('hex')]));
fs.writeFileSync(path.join(dist, 'build.json'), JSON.stringify({ version: manifest.version, builtAt: new Date().toISOString(), files: hashes, zipSha256: createHash('sha256').update(fs.readFileSync(zip)).digest('hex') }, null, 2));
console.log(zip); console.log(demoZip);
