const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const source = fs.readFileSync(require('node:path').join(__dirname, '../lib.js'), 'utf8');
  const { sanitize, safeFilename, safeFolder, suggest, prepareJobs, applyFilters, buildName, buildFolder, groupOf } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
  assert.equal(sanitize('CON'), '_CON');
  assert.equal(sanitize('LPT1.txt'), '_LPT1.txt');
  assert.equal(sanitize('a:b/c<d>?'), 'a_b_c_d__');
  assert.equal(sanitize('\u202ereport'), 'report');
  assert.equal(safeFolder('../../Reviewed/..'), 'Reviewed');
  assert.equal(safeFilename('review.TXT', 'pdf'), 'review.pdf');
  assert.equal(safeFilename('', 'pdf'), 'document.pdf');
  const item = { url: 'https://example.com/001.pdf', base: '001', ext: 'pdf', text: 'Download PDF', nearby: 'Annual Review', section: 'Finance' };
  assert.deepEqual(suggest(item), { name: 'Annual Review.pdf', folder: 'Finance', basis: 'Nearby label' });
  assert.equal(suggest({ ...item, text: 'Budget (PDF)' }).name, 'Budget.pdf');
  assert.equal(suggest({ ...item, text: '', nearby: '' }).name, '001.pdf');
  const rows = prepareJobs([{ ...item, name: 'Report.pdf', folder: 'Finance' }, { ...item, name: 'report.PDF', folder: 'Finance' }]);
  assert.equal(rows[1].path, 'Batch Grab/Finance/report (2).pdf');
  assert.equal(prepareJobs([{ ...item, name: 'Report.pdf', folder: 'Finance' }], 'Batch Grab', [rows[0].path])[0].name, 'Report (2).pdf');
  assert.throws(() => prepareJobs([{ ...item, url: 'javascript:alert(1)' }]));
  assert.equal(applyFilters([{ ...item, name: 'Annual Review.pdf', group: 'Documents' }], { groups: new Set(['Documents']), text: 'Annual', minWidth: 0 }).length, 1);
  assert.equal(buildName('{n}-{name}-{host}', { base: 'source', ext: 'pdf', host: 'example.com' }, 2, 12), '02-source-example.com.pdf');
  assert.equal(buildFolder('{host}/{date}', { host: 'example.com' }, new Date('2026-10-17T12:00:00Z')), 'example.com/2026-10-17');
  assert.equal(groupOf('docx'), 'Documents');
  assert.equal(groupOf('webp'), 'Images');
  assert.equal(groupOf('zip'), 'Archives');
  assert.equal(groupOf('mp4'), 'Media');
  const images = [{ url: 'https://x/a.png', group: 'Images', kind: 'image', w: 40 }, { url: 'https://x/b.png', group: 'Images', kind: 'image', w: 120 }];
  assert.equal(applyFilters(images, { groups: new Set(['Images']), text: '', minWidth: 100 }).length, 1);
  assert.equal(applyFilters(images, { groups: new Set(['Images']), text: '/b\\.png$/i', minWidth: 0 }).length, 1);
  assert.equal(applyFilters(images, { groups: new Set(['Documents']), text: '', minWidth: 0 }).length, 0);
  console.log('PASS: 23 naming, safety, templates, type, regex and width-filter assertions');
})();
